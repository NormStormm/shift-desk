"""Builds eval/REPORT.md: every test request next to what Claude answered in each run.

    python3 eval/make_report.py eval/results/<run1>.json eval/results/<run2>.json

Marks come from the results files, so each run is graded with the answer key it was run under
(see docs/findings.md, F4, for the four key corrections made between runs).
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).parent
cases = json.loads((HERE.parent / "test-data" / "requests.json").read_text())
runs = [json.loads(pathlib.Path(p).read_text()) for p in sys.argv[1:]]
by_id = [{r["id"]: r for r in run["results"]} for run in runs]


def cell(text):
    return str(text or "").replace("|", "\\|").replace("\n", " ")


def mark(ok):
    return "✓" if ok else "❌"


def answer(r):
    if not r:
        return "n/a"
    g = r["got"]
    if g.get("error") and not g.get("category"):
        return "❌ error: " + cell(g["error"])
    return (f"{mark(r['catOk'])} {g.get('category')}<br>{mark(r['urgOk'])} {g.get('urgency')}"
            f"<br>{mark(r['routeOk'])} {g.get('route')} ({g.get('confidence')})")


def score(run, key):
    n = len(run["results"])
    ok = sum(1 for r in run["results"] if r[key])
    return f"{ok}/{n} ({round(100 * ok / n)}%)"


lines = [
    "# Test results: all 40 requests",
    "",
    "Each row: the request sent to Shift Desk, the answer key, and what Claude answered in each run.",
    "Each answer cell shows category, urgency, and route (with Claude's confidence). ✓ = matches the key, ❌ = miss.",
    "",
    "| | " + " | ".join(f"Run {i + 1}" for i in range(len(runs))) + " |",
    "|---|" + "---|" * len(runs),
]
for label, key in [("Category", "catOk"), ("Urgency", "urgOk"), ("Route", "routeOk")]:
    lines.append(f"| {label} | " + " | ".join(score(run, key) for run in runs) + " |")
lines += [
    "",
    "Run 1 is the first prompt. Run 2 follows the urgency-definition fix (F3) and four answer-key corrections (F4),",
    "all written down *before* run 2. See [docs/findings.md](../docs/findings.md).",
    "Route: **AUTO** = sent straight to the team, **REVIEW** = a person checks first.",
    "",
    "| ID | From · Room | Request | Expected | " + " | ".join(f"Run {i + 1}" for i in range(len(runs)))
    + " | Claude's summary (last run) |",
    "|---|---|---|---|" + "---|" * len(runs) + "---|",
]
for c in cases:
    exp = c["expected"]
    expected = f"{exp['category']}<br>{exp['urgency']}<br>{'REVIEW' if exp.get('needs_review') else 'AUTO'}"
    last = by_id[-1].get(c["id"], {}).get("got", {})
    summary = cell(last.get("summary"))
    if last.get("review_reason"):
        summary += f"<br>*Review: {cell(last['review_reason'])}*"
    if last.get("urgency_note"):
        summary += f"<br>*Urgency note: {cell(last['urgency_note'])}*"
    request = f"“{cell(c['message'])}”" if c["message"].strip() else "*(empty message)*"
    if c.get("note"):
        request += f"<br>*Test note: {cell(c['note'])}*"
    lines.append(f"| **{c['id']}** | {cell(c['from'])} · {cell(c['room']) or '-'} | {request} | {expected} | "
                 + " | ".join(answer(b.get(c["id"])) for b in by_id) + f" | {summary} |")

lines += ["", "*All requests are fake test data. Generated by `eval/make_report.py`.*", ""]
out = HERE / "REPORT.md"
out.write_text("\n".join(lines))
print("wrote", out)
